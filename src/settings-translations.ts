export function settingsMessages(language: SettingsLanguage): Record<string, string> {
  return language === "ru" ? russianSettings : englishSettings;
}

export function settingsTranslator(language: SettingsLanguage): (message: string) => string {
  const messages = settingsMessages(language);
  return (message) => Object.hasOwn(messages, message) ? messages[message] : message;
}
